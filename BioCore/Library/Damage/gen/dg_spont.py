SP = {r.lean_ident.split(".")[-1]: r for r in sp.itertuples()}
TOK = re.compile(r"([A-Z][a-z]?)(\d*)")
def comp(ident):
    r = SP[ident]; c = {}
    for s, n in TOK.findall(r.formula):
        c[s] = c.get(s, 0) + int(n or 1)
    c["charge"] = int(r.charge)
    return c
def imbalance(terms):
    t = {}
    for k, ident in terms:
        for s, n in comp(ident).items():
            t[s] = t.get(s, 0) + k * n
    return {s: n for s, n in t.items() if n}
def nm(ident):
    r = SP[ident]; return r.name
def eqtext(terms):
    L = " + ".join((f"{-k} " if k != -1 else "") + nm(i) for k, i in terms if k < 0)
    R = " + ".join((f"{k} " if k != 1 else "") + nm(i) for k, i in terms if k > 0)
    return f"{L} = {R}"
def lean(terms): return "[" + ", ".join(f"({k}, {i})" for k, i in terms) + "]"

