#!/usr/bin/env python3
"""Gene library (track gn): generation of one Lean module per record (level K statements).

Methods (gn_choices.md, 8.2): M1 list literals + `decide`; M2 list literals + `decide +kernel`;
M3 packed literals (BioCore.Library.Genes.Pack) + `decide +kernel`.
The protein literal of an ACCEPTED_EQUAL record is written from the flat file's /translation string.
"""
import re

AAORD = "ARNDCQEGHILKMFPSTWYVU"
MOD_PREFIX = "BioCore.Library.Genes.Rec."
REL_DIR = "BioCore/Library/Genes/Rec"


def ident(rec_id):
    s = re.sub(r"[^A-Za-z0-9_]", "_", rec_id)
    if not re.match(r"^[A-Za-z_]", s):
        s = "R_" + s
    return s


QUALIFIED = False  # True: write `DNt.A` / `AA.M` instead of `.A` / `.M` (same terms, cheaper to elaborate)


def dna_list(s):
    assert set(s) <= set("ACGT")
    pre = "DNt." if QUALIFIED else "."
    return "[" + ", ".join(pre + ch for ch in s) + "]"


def aa_list(s):
    assert set(s) <= set(AAORD)
    pre = "AA." if QUALIFIED else "."
    return "[" + ", ".join(pre + ch for ch in s) + "]"


def pack_dna(s):
    n = 0
    for ch in s:
        n = n * 4 + "ACGT".index(ch)
    return "unpackDNA %d 0x%X" % (len(s), n)


def pack_aa(s):
    n = 0
    for ch in s:
        n = n * 32 + AAORD.index(ch)
    return "unpackAA %d 0x%X" % (len(s), n)


def reject_term(reason, pos):
    if reason == "internalStop":
        return "(.internalStop %d)" % int(pos)
    assert reason in ("notWholeCodons", "empty", "badStart", "noStop")
    return "." + reason


def module_source(r, method, noncomputable=False):
    """r: dict with id, gene, group, code ('std'|'mito'), strand, cds_stretch, cls, translation,
    x_reason, x_pos, x_protein, cds_location_raw, source_label. Returns (source, [theorem names])."""
    assert method in ("M1", "M2", "M3")
    x = ident(r["id"])
    code = {"std": "standardCode", "mito": "vertMitoCode"}[r["code"]]
    tac = "decide" if method == "M1" else "decide +kernel"
    D = pack_dna if method == "M3" else dna_list
    A = pack_aa if method == "M3" else aa_list
    DEF = "noncomputable def" if noncomputable else "def"
    L = []
    L.append("import BioCore")
    if method == "M3":
        L.append("import BioCore.Library.Genes.Pack")
    L.append("/-!")
    L.append("GENERATED by tools/gn_lean_gen.py (track gn). Level K statement for one record.")
    L.append("Record %s, gene %s, group %s. Source: %s." % (r["id"], r["gene"], r["group"], r["source_label"]))
    L.append("CDS location as annotated: %s (%d bases). Genetic code: %s. Method %s (`%s`)." % (
        r["cds_location_raw"], len(r["cds_stretch"]), code, method, tac))
    L.append("Level-X class of the record: %s." % r["cls"])
    if method == "M3":
        L.append("This statement additionally relies on the decoder in BioCore.Library.Genes.Pack.")
    if noncomputable:
        L.append("The data definitions are `noncomputable` only so that no program code is generated for them")
        L.append("(the compiled file stays small); the kernel checks the statements all the same.")
    L.append("-/")
    L.append("set_option maxRecDepth 100000000")
    L.append("set_option maxHeartbeats 0")
    L.append("namespace BioCore.Genes")
    L.append("open BioCore")
    L.append("")
    if r["strand"] == "-":
        L.append("/-- The annotated stretch on the record's strand; the gene is on the other strand. -/")
        L.append(DEF + " %s.stretch : List DNt := %s" % (x, D(r["cds_stretch"])))
        L.append("/-- Coding strand: the kernel's reverse complement of the stretch. -/")
        L.append(DEF + " %s.cds : List DNt := revComp %s.stretch" % (x, x))
    else:
        L.append("/-- Coding strand, exactly the annotated stretch. -/")
        L.append(DEF + " %s.cds : List DNt := %s" % (x, D(r["cds_stretch"])))
    ann = r["translation"]
    ann_ok = set(ann) <= set(AAORD)
    thms = []
    lhs = "decodeCDS %s (transcribe %s.cds)" % (code, x)
    if r["cls"] == "ACCEPTED_EQUAL":
        L.append("/-- The annotated protein (/translation of the flat file). -/")
        L.append(DEF + " %s.protein : List AA := %s" % (x, A(ann)))
        L.append("theorem %s.decodes : %s = .ok %s.protein := by %s" % (x, lhs, x, tac))
        thms.append("%s.decodes" % x)
    elif r["cls"] == "ACCEPTED_DIFFERENT":
        L.append("/-- The protein the kernel reads from the coding strand. -/")
        L.append(DEF + " %s.kernelProtein : List AA := %s" % (x, A(r["x_protein"])))
        L.append("theorem %s.decodes : %s = .ok %s.kernelProtein := by %s" % (x, lhs, x, tac))
        thms.append("%s.decodes" % x)
        if ann_ok:
            L.append("/-- The annotated protein (/translation of the flat file). -/")
            L.append(DEF + " %s.annotated : List AA := %s" % (x, A(ann)))
            L.append("theorem %s.differs : %s ≠ .ok %s.annotated := by %s" % (x, lhs, x, tac))
            thms.append("%s.differs" % x)
    elif r["cls"] == "REJECTED":
        if ann_ok:
            L.append("/-- The annotated protein (/translation of the flat file); no theorem is stated about it. -/")
            L.append(DEF + " %s.annotated : List AA := %s" % (x, A(ann)))
        L.append("theorem %s.rejected : %s = .rejected %s := by %s" % (x, lhs, reject_term(r["x_reason"], r["x_pos"]), tac))
        thms.append("%s.rejected" % x)
    else:
        raise ValueError("no level-K statement for class %r" % r["cls"])
    L.append("")
    for t in thms:
        L.append("#print axioms %s" % t)
    L.append("")
    L.append("end BioCore.Genes")
    return "\n".join(L) + "\n", thms


def batch_root_source(mod_names):
    return "".join("import %s\n" % m for m in mod_names)


LAKE_LINE = re.compile(r"^(\S) \[(\d+)/(\d+)\] (Built|Building|Replayed|Fetched|Ran|Running) (\S+)(?: \(([^)]*)\))?\s*$")
AX_LINE = re.compile(r"'([^']+)' depends on axioms: \[([^\]]*)\]")
AX_NONE = re.compile(r"'([^']+)' does not depend on any axioms")


def parse_time(s):
    """Lake's elapsed time text -> seconds (e.g. `309ms`, `1.8s`, `2m 3s`, `1h 2m`)."""
    if s is None:
        return None
    tot = 0.0
    found = False
    for val, unit in re.findall(r"(\d+(?:\.\d+)?)\s*(ms|s|m|h)", s):
        found = True
        tot += float(val) * {"ms": 0.001, "s": 1.0, "m": 60.0, "h": 3600.0}[unit]
    return tot if found else None


def parse_lake_log(text):
    """-> {module: {mark, action, seconds, time_text, messages[], axioms{thm: [..]}}} from `lake build` output."""
    res = {}
    cur = None
    for line in text.splitlines():
        m = LAKE_LINE.match(line)
        if m:
            mark, _, _, action, target, t = m.groups()
            cur = {"mark": mark, "action": action, "seconds": parse_time(t), "time_text": t, "messages": [], "axioms": {}}
            res[target] = cur
            continue
        if cur is not None:
            cur["messages"].append(line)
            a = AX_LINE.search(line)
            if a:
                cur["axioms"][a.group(1)] = [s.strip() for s in a.group(2).split(",") if s.strip()]
            a = AX_NONE.search(line)
            if a:
                cur["axioms"][a.group(1)] = []
    return res
